"""Regenerate the committed G2+G3 calibration fixture. Not a test.

    python tests/eval/recall_calibration/make_calibration_fixture.py

**This corpus is synthetic and the fixture says so in its own header.** It exists so the
calibration lane can run — and be red — on a bare checkout, months before the MSHA and CSB
ingestion lands. Every artefact produced from it is stamped ``SYNTHETIC`` and
``PRELIMINARY``, so a passing run can never be mistaken for a measurement of the product.
When a real G2/G3 set exists, point ``TRAPPOINT_RECALL_CALIBRATION_SET`` at it and the same
lane measures that instead; the resolution rule refuses to fall back silently.

What the generator imitates, and why each part is there:

* **Two gold sets with different label quality.** G3 is adjudicated and its labels track the
  score closely; G2 is structured-code co-membership, which is weak supervision — plenty of
  positives that share an accident classification and nothing else. A calibrator fitted
  mostly on G2 is fitted mostly on noise, and the report has to be able to show that.
* **A miscalibrated raw score.** The scalar is deliberately over-confident in the middle of
  its range. If the raw score were already calibrated, the isotonic fit would have nothing to
  do and the lane would pass while measuring nothing.
* **Drift across time blocks.** The base rate moves between half-years. That is what makes
  the temporally-blocked split a real constraint rather than a naming convention, and it is
  the honest reason conformal exchangeability is an assumption rather than a guarantee.
"""

from __future__ import annotations

import json
import math
import random
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any, Final

HERE: Final = Path(__file__).resolve().parent
FIXTURE: Final = HERE / "fixtures" / "calibration_g2g3.json"

SCHEMA: Final = "mainline.recall.calibration_set/1"
SEED: Final = 20260804
N_PER_BLOCK: Final = 90

#: Half-year blocks. The wall in the fixture header falls exactly on a block boundary, so no
#: block can straddle it — a fold on both sides of the wall would be a leak with a plausible
#: name.
BLOCKS: Final[tuple[tuple[str, datetime], ...]] = (
    ("2019H1", datetime(2019, 1, 1, tzinfo=UTC)),
    ("2019H2", datetime(2019, 7, 1, tzinfo=UTC)),
    ("2020H1", datetime(2020, 1, 1, tzinfo=UTC)),
    ("2020H2", datetime(2020, 7, 1, tzinfo=UTC)),
    ("2021H1", datetime(2021, 1, 1, tzinfo=UTC)),
    ("2021H2", datetime(2021, 7, 1, tzinfo=UTC)),
)

WALL: Final = datetime(2021, 1, 1, tzinfo=UTC)
CORPUS_COMMIT: Final = "synthetic-calibration-fixture-1"


def _sigmoid(value: float) -> float:
    return 1.0 / (1.0 + math.exp(-value))


def _true_probability(score: float, gold_set: str, drift: float) -> float:
    """The label-generating process. Monotone in the score, weaker for G2, drifting in time."""
    sharp = _sigmoid(1.4 * (score - 0.6) + drift)
    if gold_set == "G3":
        return sharp
    # G2 is structured-code co-membership: a large, automatable, noisy signal. Compressed
    # toward the base rate, because "same accident classification" is a weak positive.
    return 0.18 + 0.55 * sharp


def build() -> dict[str, Any]:
    rng = random.Random(SEED)  # noqa: S311 - synthetic fixture data, not a key
    samples: list[dict[str, Any]] = []
    for block_index, (fold, block_start) in enumerate(BLOCKS):
        drift = -0.35 + 0.14 * block_index
        for index in range(N_PER_BLOCK):
            gold_set = "G3" if index % 3 == 0 else "G2"
            score = rng.uniform(-2.0, 3.0)
            probability = _true_probability(score, gold_set, drift)
            occurred = block_start + timedelta(days=rng.randint(0, 150), hours=rng.randint(0, 23))
            ingested = occurred + timedelta(days=rng.randint(1, 20))
            samples.append(
                {
                    "doc_id": f"SYN-{fold}-{index:03d}",
                    "gold_set": gold_set,
                    "fold": fold,
                    "raw_score": round(score, 9),
                    "label": 1 if rng.random() < probability else 0,
                    "occurred_at": occurred.isoformat(),
                    "ingested_at": ingested.isoformat(),
                    "corpus_commit_at": (block_start + timedelta(days=170)).isoformat(),
                }
            )

    positives = sum(sample["label"] for sample in samples)
    return {
        "schema": SCHEMA,
        "synthetic": True,
        "preliminary": True,
        "note": "Synthetic G2+G3 stand-in. Generated by make_calibration_fixture.py so the "
        "calibration lane runs on a bare checkout. These numbers characterise the "
        "calibrator implementation, not the product.",
        "seed": SEED,
        "corpus_commit": CORPUS_COMMIT,
        "wall": WALL.isoformat(),
        "blocks": [fold for fold, _ in BLOCKS],
        "n_samples": len(samples),
        "n_positive": positives,
        "samples": samples,
    }


def main() -> int:
    document = build()
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(document, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {document['n_samples']} samples ({document['n_positive']} positive) to {FIXTURE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
